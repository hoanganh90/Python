# Higher order functions
# A higher order function is a function that takes another function as an argument or returns a function as its result.
# In Python, functions are first-class citizens, meaning they can be passed around as arguments, returned from other functions, and assigned to variables.
def greet(name):
    return f"Hello, {name}!"
def greet_with_exclamation(name):
    return f"Hello, {name}!"
def greet_with_question(name):
    return f"Hello, {name}?"
